package com.aytmatech.querier.ai.query;

import com.aytmatech.querier.Select;
import java.util.*;

/**
 * The result of a natural-language query generation request.
 *
 * <p>Always contains the original prompt and the validated rawSql. The compiled {@link Select} is
 * present when validation succeeded. Callers can inspect the plan and query before deciding to
 * execute.
 *
 * <pre>{@code
 * QueryResult result = querierAi.query(request);
 * if (result.isValid()) {
 *     Select query = result.query().orElseThrow();
 *     List<Map<String, Object>> rows = jdbcRunner.run(query);
 * } else {
 *     result.validationIssues().forEach(System.err::println);
 * }
 * }</pre>
 */
public final class QueryResult {

  private final String prompt;
  private final Select query;
  private final List<String> validationIssues;
  private final String interpretationNote;
  private final String rawSql;

  private QueryResult(Builder b) {
    this.prompt = Objects.requireNonNull(b.prompt, "prompt");
    this.query = b.query;
    this.validationIssues = Collections.unmodifiableList(new ArrayList<>(b.validationIssues));
    this.interpretationNote = b.interpretationNote;
    this.rawSql = b.rawSql;
  }

  /**
   * Creates a new {@link Builder} instance for constructing a {@link QueryResult}.
   *
   * @return A new {@link Builder} instance for constructing a {@link QueryResult}.
   */
  public static Builder builder() {
    return new Builder();
  }

  /**
   * The original natural-language prompt.
   *
   * @return The original natural-language prompt.
   */
  public String prompt() {
    return prompt;
  }

  /**
   * The compiled Querier {@link Select}, present only when {@link #isValid()} is {@code true}.
   *
   * @return The compiled Querier {@link Select}, present only when {@link #isValid()} is {@code
   *     true}.
   */
  public Optional<Select> query() {
    return Optional.ofNullable(query);
  }

  /**
   * Whether the plan passed validation and was successfully compiled.
   *
   * @return Whether the plan passed validation and was successfully compiled.
   */
  public boolean isValid() {
    return query != null && validationIssues.isEmpty();
  }

  /**
   * Structured validation issues. Non-empty when the plan was invalid or ambiguous.
   *
   * @return Structured validation issues. Non-empty when the plan was invalid or ambiguous.
   */
  public List<String> validationIssues() {
    return validationIssues;
  }

  /**
   * Optional note explaining how the AI interpreted ambiguous terminology in the prompt.
   *
   * @return Optional note explaining how the AI interpreted ambiguous terminology in the prompt.
   */
  public Optional<String> interpretationNote() {
    return Optional.ofNullable(interpretationNote);
  }

  /**
   * Returns the raw SQL string generated by the AI, if available. This may be present even if the
   * query is invalid, for debugging purposes.
   *
   * @return The raw SQL string generated by the AI, if available. This may be present even if the
   *     query is invalid, for debugging purposes.
   */
  public Optional<String> rawSql() {
    return Optional.ofNullable(rawSql);
  }

  /** Builder class for constructing {@link QueryResult} instances. */
  public static final class Builder {
    private String prompt;
    private Select query;
    private final List<String> validationIssues = new ArrayList<>();
    private String interpretationNote;
    // In the Builder:
    private String rawSql;

    private Builder() {}

    /**
     * Sets the raw SQL string generated by the AI, if available. This may be present even if the
     * query is invalid, for debugging purposes.
     *
     * @param rawSql the raw SQL string generated by the AI, if available. This may be present even
     *     if the query is invalid, for debugging purposes.
     * @return this builder
     */
    public Builder rawSql(String rawSql) {
      this.rawSql = rawSql;
      return this;
    }

    /**
     * Sets the original natural-language prompt.
     *
     * @param prompt the original natural-language prompt
     * @return this builder
     */
    public Builder prompt(String prompt) {
      this.prompt = prompt;
      return this;
    }

    /**
     * Sets the compiled Querier {@link Select}, present only when {@link #isValid()} is {@code
     * true}.
     *
     * @param query the compiled Querier {@link Select}, present only when {@link #isValid()} is
     *     {@code true}
     * @return this builder
     */
    public Builder query(Select query) {
      this.query = query;
      return this;
    }

    /**
     * Adds a validation issue to the list of issues. Non-empty when the plan was invalid or
     * ambiguous.
     *
     * @param issue a validation issue to add to the list of issues
     * @return this builder
     */
    public Builder validationIssue(String issue) {
      this.validationIssues.add(issue);
      return this;
    }

    /**
     * Sets an optional note explaining how the AI interpreted ambiguous terminology in the prompt.
     *
     * @param interpretationNote Optional note explaining how the AI interpreted ambiguous
     *     terminology in the prompt.
     * @return this builder
     */
    public Builder interpretationNote(String interpretationNote) {
      this.interpretationNote = interpretationNote;
      return this;
    }

    /**
     * Validation issues are stored as an unmodifiable copy of the list of validation issues.
     * Non-empty when the plan was invalid or ambiguous.
     *
     * @return an unmodifiable copy of the list of validation issues. Non-empty when the plan was
     *     invalid or ambiguous.
     */
    public List<String> getValidationIssues() {
      return List.copyOf(validationIssues);
    }

    /**
     * Builds a new {@link QueryResult} instance from the current state of this builder.
     *
     * @return a new {@link QueryResult} instance built from the current state of this builder
     */
    public QueryResult build() {
      return new QueryResult(this);
    }
  }
}
