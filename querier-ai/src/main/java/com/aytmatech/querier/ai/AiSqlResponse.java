package com.aytmatech.querier.ai;

import java.util.Optional;

/**
 * The structured JSON response from the AI when using SQL-first mode. The AI returns only SQL — not
 * a proprietary plan IR.
 */
public final class AiSqlResponse {

  private final String sql;
  private final boolean ambiguous;
  private final String ambiguityNote;

  private AiSqlResponse(String sql, boolean ambiguous, String ambiguityNote) {
    this.sql = sql;
    this.ambiguous = ambiguous;
    this.ambiguityNote = ambiguityNote;
  }

  /**
   * Creates a new {@link AiSqlResponse} with the given SQL.
   *
   * @param sql The SQL generated by the AI.
   * @return An {@link AiSqlResponse} containing the SQL.
   */
  public static AiSqlResponse ofSql(String sql) {
    return new AiSqlResponse(sql, false, null);
  }

  /**
   * Creates a new {@link AiSqlResponse} indicating that the AI was unable to generate SQL due to
   * ambiguity.
   *
   * @param note A note explaining why the AI was unable to generate SQL.
   * @return An {@link AiSqlResponse} indicating that the AI was unable to generate SQL due to
   *     ambiguity.
   */
  public static AiSqlResponse ambiguous(String note) {
    return new AiSqlResponse(null, true, note);
  }

  /**
   * Returns the SQL generated by the AI, if any.
   *
   * @return An {@link Optional} containing the SQL generated by the AI, or empty if the AI was
   *     unable to generate SQL due to ambiguity.
   */
  public Optional<String> sql() {
    return Optional.ofNullable(sql);
  }

  /**
   * Returns true if the AI was unable to generate SQL due to ambiguity, false otherwise.
   *
   * @return true if the AI was unable to generate SQL due to ambiguity, false otherwise.
   */
  public boolean isAmbiguous() {
    return ambiguous;
  }

  /**
   * Returns a note explaining why the AI was unable to generate SQL due to ambiguity, if any.
   *
   * @return An {@link Optional} containing a note explaining why the AI was unable to generate SQL
   *     due to ambiguity, or empty if the AI generated SQL successfully.
   */
  public Optional<String> ambiguityNote() {
    return Optional.ofNullable(ambiguityNote);
  }
}
