package com.aytmatech.querier.ai.analytics;

import com.aytmatech.querier.dashboard.Dashboard;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Optional;

/**
 * The result of an AI dashboard generation request.
 *
 * <p>On success ({@link #isValid()} is {@code true}), {@link #dashboard()} contains a fully
 * compiled Querier {@link Dashboard} ready to pass to {@link
 * com.aytmatech.querier.dashboard.DashboardRenderer}.
 *
 * <p>On failure, {@link #validationIssues()} describes what went wrong. A partially valid dashboard
 * is never returned — success is atomic.
 *
 * <pre>{@code
 * DashboardResult result = querierAi.dashboard(request);
 * if (result.isValid()) {
 *     String html = DashboardRenderer.builder()
 *         .dashboard(result.dashboard().orElseThrow())
 *         .queryRunner(runner)
 *         .build()
 *         .renderHtml();
 * } else {
 *     result.validationIssues().forEach(System.err::println);
 * }
 * }</pre>
 */
public final class DashboardResult {

  private final String prompt;
  private final DashboardPlan plan;
  private final Dashboard dashboard;
  private final List<String> validationIssues;
  private final String interpretationNote;

  private DashboardResult(Builder b) {
    this.prompt = b.prompt;
    this.plan = b.plan;
    this.dashboard = b.dashboard;
    this.validationIssues = Collections.unmodifiableList(new ArrayList<>(b.validationIssues));
    this.interpretationNote = b.interpretationNote;
  }

  /**
   * Returns a new builder for {@link DashboardResult}.
   *
   * @return A new {@link Builder} for constructing a {@link DashboardResult} instance.
   */
  public static Builder builder() {
    return new Builder();
  }

  /**
   * The original prompt that generated this dashboard result. Useful for logging and debugging.
   *
   * @return The original natural-language prompt.
   */
  public String prompt() {
    return prompt;
  }

  /**
   * The structured plan generated by the AI. Useful for debugging and logging.
   *
   * @return The structured dashboard plan produced by the AI. May be {@code null} if parsing
   *     failed.
   */
  public DashboardPlan plan() {
    return plan;
  }

  /**
   * The compiled Querier {@link Dashboard} ready to render. Present only if {@link #isValid()} is
   * {@code true}.
   *
   * @return The compiled {@link Dashboard}, present only when {@link #isValid()} is {@code true}.
   *     The dashboard is a plain Querier object — the AI dependency is not required at render time.
   */
  public Optional<Dashboard> dashboard() {
    return Optional.ofNullable(dashboard);
  }

  /**
   * Whether the dashboard result is valid and ready to render. If {@code false}, {@link
   * #validationIssues()} describes what went wrong.
   *
   * @return Whether the plan passed validation and was successfully compiled.
   */
  public boolean isValid() {
    return dashboard != null && validationIssues.isEmpty();
  }

  /**
   * Structured validation issues describing what went wrong. Present only if {@link #isValid()} is
   * {@code false}.
   *
   * @return Structured validation issues. Non-empty when the plan was invalid.
   */
  public List<String> validationIssues() {
    return validationIssues;
  }

  /**
   * Interpretation note from the AI, if any. May be {@code null}. Useful for logging and debugging.
   *
   * @return Optional note explaining how ambiguous terminology in the prompt was interpreted.
   */
  public Optional<String> interpretationNote() {
    return Optional.ofNullable(interpretationNote);
  }

  /** Builder for {@link DashboardResult}. Use {@link #builder()} to create a new instance. */
  public static final class Builder {
    private String prompt;
    private DashboardPlan plan;
    private Dashboard dashboard;
    private final List<String> validationIssues = new ArrayList<>();
    private String interpretationNote;

    private Builder() {}

    /**
     * The original prompt that generated this dashboard result. Useful for logging and debugging.
     *
     * @param prompt The original natural-language prompt that was sent to the AI.
     * @return this builder
     */
    public Builder prompt(String prompt) {
      this.prompt = prompt;
      return this;
    }

    /**
     * The structured plan generated by the AI. Useful for debugging and logging.
     *
     * @param plan The structured dashboard plan produced by the AI. May be {@code null} if parsing
     *     failed.
     * @return this builder
     */
    public Builder plan(DashboardPlan plan) {
      this.plan = plan;
      return this;
    }

    /**
     * The compiled Querier {@link Dashboard} ready to render. Present only if {@link #isValid()} is
     * {@code true}.
     *
     * @param dashboard The compiled Querier {@link Dashboard}, present only when {@link #isValid()}
     *     is {@code true}.
     * @return this builder
     */
    public Builder dashboard(Dashboard dashboard) {
      this.dashboard = dashboard;
      return this;
    }

    /**
     * Structured validation issues describing what went wrong. Present only if {@link #isValid()}
     * is {@code false}.
     *
     * @param validationIssue A structured validation issue describing what went wrong. Non-empty
     *     when the plan was invalid.
     * @return this builder
     */
    public Builder validationIssue(String validationIssue) {
      this.validationIssues.add(validationIssue);
      return this;
    }

    /**
     * Interpretation note from the AI, if any. May be {@code null}. Useful for logging and
     * debugging.
     *
     * @param interpretationNote An optional note explaining how ambiguous terminology in the prompt
     *     was interpreted.
     * @return this builder
     */
    public Builder interpretationNote(String interpretationNote) {
      this.interpretationNote = interpretationNote;
      return this;
    }

    /**
     * Builds the {@link DashboardResult} instance.
     *
     * @return a new {@link DashboardResult} instance built from the current state of this builder.
     */
    public DashboardResult build() {
      return new DashboardResult(this);
    }
  }
}
